export const getProductBySlug = (slug) => products.find((product) => product.slug === slug)

export const getRelatedProducts = (currentProduct, limit = 4) => {
  if (!currentProduct) return []
  return products
    .filter((product) => product.id !== currentProduct.id)
    .sort((left, right) => Number(right.category === currentProduct.category) - Number(left.category === currentProduct.category))
    .slice(0, limit)
}
